#!/usr/bin/env node
/**
 * Generates two blocks of AGENTS.md from the repo, so they cannot go stale (#340, #368):
 *   - the "Project Structure" tree, from the filesystem and `scripts/structure-doc.json`;
 *   - the layer table, from `scripts/architecture.json` (the same file the import rules are built from).
 *   node scripts/gen-structure-doc.mjs           rewrite the tree
 *   node scripts/gen-structure-doc.mjs --check   exit 1 when it is stale
 *
 * `scripts/structure-doc.json` holds the curated entries — `{ path, note? }`,
 * in display order, a trailing `/` for directories, `*` / `{a,b}` globs allowed.
 * Every entry must exist (a glob must match something) or the script fails, and
 * every top-level `src/` folder is listed even without an entry. An entry with
 * `"optional": true` names a generated tree (`build/`, `cpp/build-*`) that exists
 * only after a build: it is rendered but never checked, so `--check` gives the
 * same answer before and after `npm run build` (#358).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const agentsPath = path.join(root, 'AGENTS.md');
const entriesPath = path.join(root, 'scripts', 'structure-doc.json');
const BEGIN = '<!-- structure:begin (generated by scripts/gen-structure-doc.mjs — edit scripts/structure-doc.json) -->';
const END = '<!-- structure:end -->';
const LAYERS_BEGIN = '<!-- layers:begin (generated by scripts/gen-structure-doc.mjs — edit scripts/architecture.json) -->';
const LAYERS_END = '<!-- layers:end -->';
const architecturePath = path.join(root, 'scripts', 'architecture.json');
const NOTE_COLUMN = 37;

function globToRegExp(pattern) {
  const source = pattern
    .replace(/[.+^$()|[\]\\]/g, '\\$&')
    .replace(/\{([^}]*)\}/g, (_, alts) => `(${alts.split(',').join('|')})`)
    .replace(/\*/g, '[^/]*');
  return new RegExp(`^${source}$`);
}

function exists(entryPath) {
  const clean = entryPath.replace(/\/$/, '');
  if (!/[*{]/.test(clean)) return fs.existsSync(path.join(root, clean));
  const dir = path.dirname(clean);
  const re = globToRegExp(path.basename(clean));
  const abs = path.join(root, dir);
  return fs.existsSync(abs) && fs.readdirSync(abs).some((name) => re.test(name));
}

function loadEntries() {
  const entries = JSON.parse(fs.readFileSync(entriesPath, 'utf8'));
  const missing = entries.filter((e) => !e.optional && !exists(e.path)).map((e) => e.path);
  if (missing.length) {
    throw new Error(`structure-doc.json lists paths that do not exist:\n  ${missing.join('\n  ')}`);
  }
  const listed = new Set(entries.map((e) => e.path));
  for (const dirent of fs.readdirSync(path.join(root, 'src'), { withFileTypes: true })) {
    const p = `src/${dirent.name}/`;
    if (dirent.isDirectory() && !listed.has(p)) entries.push({ path: p });
  }
  return entries;
}

/** Build a tree keyed by path segment, children in first-seen order. */
function buildTree(entries) {
  const top = { children: new Map() };
  for (const { path: p, note } of entries) {
    const isDir = p.endsWith('/');
    const parts = p.replace(/\/$/, '').split('/');
    let node = top;
    parts.forEach((part, i) => {
      if (!node.children.has(part)) node.children.set(part, { children: new Map(), isDir: i < parts.length - 1 });
      node = node.children.get(part);
    });
    if (isDir) node.isDir = true;
    if (note) node.note = note;
  }
  return top;
}

function render(node, prefix, out) {
  const kids = [...node.children.entries()];
  kids.forEach(([name, child], i) => {
    const last = i === kids.length - 1;
    const label = `${prefix}${last ? '└── ' : '├── '}${name}${child.isDir ? '/' : ''}`;
    out.push(child.note ? `${label.padEnd(NOTE_COLUMN)}${label.length >= NOTE_COLUMN ? ' ' : ''}# ${child.note}` : label);
    render(child, `${prefix}${last ? '    ' : '│   '}`, out);
  });
}

function generate() {
  const out = ['```', 'webgpu_streetview/'];
  render(buildTree(loadEntries()), '', out);
  out.push('```');
  return `${BEGIN}\n${out.join('\n')}\n${END}`;
}

function generateLayers() {
  const { layers, packages = {} } = JSON.parse(fs.readFileSync(architecturePath, 'utf8'));
  const rows = [...layers].reverse().map((layer, i) => {
    const level = layers.length - i;
    const folders = layer.folders.map((f) => `\`${f}/\``).join(', ');
    const below = layers.slice(0, level - 1).flatMap((l) => l.folders);
    const may = below.length ? `itself, ${layers.slice(0, level - 1).map((l) => l.name).join(', ')}` : 'itself only';
    return `| ${level} | **${layer.name}** | ${folders} | ${layer.note} | ${may} |`;
  });
  return [
    LAYERS_BEGIN,
    '| # | Layer | Folders | What lives here | May import |',
    '|---|---|---|---|---|',
    ...rows,
    '',
    '**Packages** — a higher layer imports these only through their public entry (`only-through-entry-*` rule):',
    '',
    '| Folder | Entries | Notes |',
    '|---|---|---|',
    ...Object.entries(packages).map(([pkg, { entries, note }]) => `| \`${pkg}/\` | ${entries.map((e) => `\`${e}\``).join(', ')} | ${note} |`),
    LAYERS_END,
  ].join('\n');
}

function splice(text, begin, end, block) {
  const b = text.indexOf(begin);
  const e = text.indexOf(end);
  if (b < 0 || e < b) {
    console.error(`AGENTS.md has no ${begin} … ${end} block`);
    process.exit(1);
  }
  return text.slice(0, b) + block + text.slice(e + end.length);
}

const doc = fs.readFileSync(agentsPath, 'utf8');
let next = splice(doc, BEGIN, END, generate());
next = splice(next, LAYERS_BEGIN, LAYERS_END, generateLayers());
if (process.argv.includes('--check')) {
  if (next !== doc) {
    console.error('AGENTS.md structure tree / layer table is stale — run `npm run gen:structure-doc`.');
    process.exit(1);
  }
} else if (next !== doc) {
  fs.writeFileSync(agentsPath, next);
  console.log('Wrote the AGENTS.md structure tree and layer table.');
}
